#!/bin/sh
set -eu

# Выполняется администратором только при инициализации нового volume.
psql --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" \
    --set=ON_ERROR_STOP=1 --set=app_password="$PG_APP_PASSWORD" <<'SQL'
CREATE ROLE lab_app LOGIN PASSWORD :'app_password'
    NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;

REVOKE ALL ON DATABASE security_lab FROM PUBLIC;
GRANT CONNECT ON DATABASE security_lab TO lab_app;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;

CREATE SCHEMA lab AUTHORIZATION lab_admin;
CREATE TABLE lab.accounts (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(100) NOT NULL UNIQUE,
    display_name varchar(100) NOT NULL
);
INSERT INTO lab.accounts (username, display_name)
VALUES ('alice', 'Учебная запись Алисы'), ('bob', 'Учебная запись Боба');

GRANT USAGE ON SCHEMA lab TO lab_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA lab TO lab_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA lab TO lab_app;

-- Права для будущих объектов, создаваемых именно lab_admin в этой схеме.
ALTER DEFAULT PRIVILEGES FOR ROLE lab_admin IN SCHEMA lab
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO lab_app;
ALTER DEFAULT PRIVILEGES FOR ROLE lab_admin IN SCHEMA lab
    GRANT USAGE, SELECT ON SEQUENCES TO lab_app;
SQL
